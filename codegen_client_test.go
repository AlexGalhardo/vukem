package vukem

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func runCodegenClient(t *testing.T, args ...string) (string, *connectingProvider, error) {
	t.Helper()

	var out bytes.Buffer

	prov := &connectingProvider{}
	build := func(opts ...Option) (*App, error) {
		return New(append(opts,
			WithLogger(discardLogger()), WithStdout(&out),
			WithProviders(prov), WithRoutes(openAPIRoutes))...)
	}

	err := RunMain(t.Context(), append([]string{"app", "codegen:client"}, args...), testSource(nil).Lookup, build)

	return out.String(), prov, err
}

func TestCodegenClientCommand(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		args []string
		want []string
	}{
		{
			name: "typescript",
			args: []string{"-o", "-"},
			want: []string{
				"// Code generated by vukem codegen:client. DO NOT EDIT.",
				"ping(): Promise<PingResponse>;",
				"export function createClient(options: ClientOptions = {}): Client {",
			},
		},
		{
			name: "go",
			args: []string{"-lang", "go", "-package", "shop", "-o", "-"},
			want: []string{
				"package shop\n",
				"func (c *Client) Ping(ctx context.Context) (PingOut, error) {",
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			got, prov, err := runCodegenClient(t, tt.args...)
			if err != nil {
				t.Fatal(err)
			}

			if prov.shutdown {
				t.Error("warmup mode ran provider Shutdown without Boot")
			}

			for _, w := range tt.want {
				if !strings.Contains(got, w) {
					t.Errorf("codegen:client %v output lacks %q:\n%s", tt.args, w, got)
				}
			}
		})
	}
}

func TestCodegenClientCommand_WritesFile(t *testing.T) {
	t.Parallel()

	path := filepath.Join(t.TempDir(), "internal", "apiclient", "client.go")

	stdout, _, err := runCodegenClient(t, "-lang", "go", "-o", path)
	if err != nil || stdout != "" {
		t.Fatalf("codegen:client = %q, %v", stdout, err)
	}

	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}

	if !bytes.Contains(b, []byte("package apiclient\n")) {
		t.Errorf("client.go = %q, want package apiclient", b[:min(len(b), 200)])
	}
}

func TestCodegenClientCommand_Errors(t *testing.T) {
	t.Parallel()

	for _, args := range [][]string{{"-lang", "rust", "-o", "-"}, {"-lang", "go", "-package", "1x", "-o", "-"}} {
		if _, _, err := runCodegenClient(t, args...); err == nil {
			t.Errorf("codegen:client %v = nil error", args)
		}
	}
}
