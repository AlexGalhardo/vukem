var update = flag.Bool("update", false, "rewrite golden files")

func codegenRoutes(r *router.Router, _ *App) error {
	ok := func(*web.Ctx) error { return nil }

	r.Get("/{$}", ok).Name("home")
	r.Get("/health", ok)
	r.Get("/posts/{id}", ok).Name("posts.show")
	r.Post("/posts", ok).Name("posts.store")
	r.Get("/posts/{id}/comments/{comment}", ok).Name("comments.show")
	r.Get("/files/{path...}", ok).Name("files.show")
	r.Any("/hooks/{provider}", ok).Name("hooks")
	r.Group("/admin", func(g *router.Group) {
		g.Get("/users/{id}", ok).Name("users.edit")
	}).Name("admin.")

	return nil
}

// connectingProvider stands in for a provider that opens a connection at Boot.
type connectingProvider struct{ shutdown bool }

func (*connectingProvider) Register(*App) error { return nil }

func (*connectingProvider) Boot(context.Context, *App) error {
	return errors.New("dial tcp: connection refused")
}

func (p *connectingProvider) Shutdown(context.Context, *App) error {
	p.shutdown = true
	return nil
}

func runCodegenRoutes(t *testing.T, args ...string) (string, *connectingProvider) {
	t.Helper()

	var out bytes.Buffer

	prov := &connectingProvider{}
	build := func(opts ...Option) (*App, error) {
		return New(append(opts,
			WithLogger(discardLogger()), WithStdout(&out),
			WithProviders(prov), WithRoutes(codegenRoutes))...)
	}

	if err := RunMain(t.Context(), append([]string{"app", "codegen:routes"}, args...),
		testSource(nil).Lookup, build); err != nil {
		t.Fatal(err)
	}

	return out.String(), prov
}

func TestCodegenRoutesCommand_Golden(t *testing.T) {
	t.Parallel()

	got, prov := runCodegenRoutes(t, "-o", "-")
	if prov.shutdown {
		t.Error("warmup mode ran provider Shutdown without Boot")
	}

	golden := filepath.Join("testdata", "routes.golden.ts")
	if *update {
		if err := os.MkdirAll("testdata", 0o750); err != nil {
			t.Fatal(err)
		}

		if err := os.WriteFile(golden, []byte(got), 0o600); err != nil {
			t.Fatal(err)
		}
	}

	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatal(err)
	}

	if diff := cmp.Diff(string(want), got); diff != "" {
		t.Errorf("codegen:routes mismatch (-want +got):\n%s", diff)
	}
}

func TestCodegenRoutesCommand_WritesFile(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		args func(dir string) []string
		want string
	}{
		{
			name: "explicit file",
			args: func(dir string) []string { return []string{"-o", filepath.Join(dir, "out", "r.ts")} },
			want: filepath.Join("out", "r.ts"),
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()

			stdout, _ := runCodegenRoutes(t, tt.args(dir)...)
			if stdout != "" {
				t.Errorf("stdout = %q, want empty", stdout)
			}

			b, err := os.ReadFile(filepath.Join(dir, tt.want))
			if err != nil {
				t.Fatal(err)
			}

			if !bytes.HasPrefix(b, []byte("// Code generated by vukem codegen:routes. DO NOT EDIT.\n")) {
				t.Errorf("file header = %q", b[:min(len(b), 80)])
			}
		})
	}
}

