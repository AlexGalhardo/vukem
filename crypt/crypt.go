// Package crypt encrypts and authenticates values with AES-256-GCM and
// supports key rotation: one current key encrypts, previous keys only
// decrypt. Tokens are unpadded base64url strings, safe for cookies, URLs
// and database columns.
//
// Token layout (before base64url):
//
//	version (1 byte) | key id (4 bytes) | nonce (12) | ciphertext | tag (16)
//
// The key id lets Open pick the right key without trial decryption, and the
// header is authenticated together with the caller's additional data, so a
// token sealed for one purpose (a cookie name, a table column) cannot be
// replayed as another.
//
// Never pass APP_KEY directly: derive a purpose key with
// app.Key.Derive("crypt", crypt.KeySize). Apps get a ready Encrypter in
// app.Crypt, built from APP_KEY and APP_PREVIOUS_KEYS.
package crypt

import (
	"bytes"
	"crypto/aes"
	"crypto/cipher"
	"crypto/sha256"
	"encoding/base64"
	"errors"
	"fmt"
)

// KeySize is the required key length in bytes (AES-256).
const KeySize = 32

const (
	version    byte = 1
	keyIDSize       = 4
	headerSize      = 1 + keyIDSize
	nonceSize       = 12
	tagSize         = 16
)

// ErrInvalid is returned for every token that cannot be opened: malformed,
// tampered, sealed with an unknown key or with different additional data.
// The causes are deliberately not distinguished.
var ErrInvalid = errors.New("crypt: invalid or tampered ciphertext")

type key struct {
	id   [keyIDSize]byte
	aead cipher.AEAD
}

// Encrypter seals and opens tokens. It is safe for concurrent use.
type Encrypter struct {
	keys []key // keys[0] is the current key
}

// New returns an Encrypter that seals with current and also opens tokens
// sealed with any of previous (key rotation). Every key must be exactly
// KeySize bytes.
func New(current []byte, previous ...[]byte) (*Encrypter, error) {
	e := &Encrypter{keys: make([]key, 0, 1+len(previous))}

	for i, raw := range append([][]byte{current}, previous...) {
		if len(raw) != KeySize {
			return nil, fmt.Errorf("crypt: key %d must be %d bytes, got %d", i, KeySize, len(raw))
		}

		block, err := aes.NewCipher(raw)
		if err != nil {
			return nil, fmt.Errorf("crypt: key %d: %w", i, err)
		}

		aead, err := cipher.NewGCMWithRandomNonce(block)
		if err != nil {
			return nil, fmt.Errorf("crypt: key %d: %w", i, err)
		}

		e.keys = append(e.keys, key{id: keyID(raw), aead: aead})
	}

	return e, nil
}

// keyID identifies a key without revealing it: a truncated SHA-256 of the
// key under a domain label.
func keyID(raw []byte) [keyIDSize]byte {
	sum := sha256.Sum256(append([]byte("vukem:crypt:key-id:"), raw...))
	return [keyIDSize]byte(sum[:keyIDSize])
}

// Seal encrypts plaintext with the current key, authenticating ad
// (additional data, not stored in the token) alongside it. Open must be
// given the same ad.
func (e *Encrypter) Seal(plaintext, ad []byte) string {
	k := e.keys[0]

	out := make([]byte, headerSize, headerSize+nonceSize+len(plaintext)+tagSize)
	out[0] = version
	copy(out[1:], k.id[:])

	// The random nonce is generated by the AEAD (crypto/rand) and prefixed.
	//nolint:gosec // G407: nil is not a fixed nonce; NewGCMWithRandomNonce draws one per call
	out = k.aead.Seal(out, nil, plaintext, additional(out[:headerSize], ad))

	return base64.RawURLEncoding.EncodeToString(out)
}

// Open decrypts a token produced by Seal with the same ad, using the current
// or any previous key. Every failure returns ErrInvalid.
func (e *Encrypter) Open(token string, ad []byte) ([]byte, error) {
	raw, id, ok := parse(token)
	if !ok {
		return nil, ErrInvalid
	}

	aad := additional(raw[:headerSize], ad)

	for _, k := range e.keys {
		if k.id != id {
			continue
		}

		// Several keys may share an id only by (unlikely) collision: try each.
		if plain, err := k.aead.Open(nil, nil, raw[headerSize:], aad); err == nil {
			return plain, nil
		}
	}

	return nil, ErrInvalid
}

// Encrypt is Seal without additional data.
func (e *Encrypter) Encrypt(plaintext []byte) string { return e.Seal(plaintext, nil) }

// Decrypt is Open without additional data.
func (e *Encrypter) Decrypt(token string) ([]byte, error) { return e.Open(token, nil) }

// EncryptString encrypts s without additional data.
func (e *Encrypter) EncryptString(s string) string { return e.Seal([]byte(s), nil) }

// DecryptString decrypts a token produced by EncryptString.
func (e *Encrypter) DecryptString(token string) (string, error) {
	b, err := e.Open(token, nil)
	return string(b), err
}

// NeedsRotation reports whether token is well formed but was sealed with a
// key other than the current one; re-seal it with Rotate. It does not
// authenticate the token.
func (e *Encrypter) NeedsRotation(token string) bool {
	_, id, ok := parse(token)
	return ok && id != e.keys[0].id
}

// Rotate opens token with ad and seals the plaintext again with the current
// key.
func (e *Encrypter) Rotate(token string, ad []byte) (string, error) {
	plain, err := e.Open(token, ad)
	if err != nil {
		return "", err
	}

	return e.Seal(plain, ad), nil
}

func parse(token string) (raw []byte, id [keyIDSize]byte, ok bool) {
	raw, err := base64.RawURLEncoding.Strict().DecodeString(token)
	if err != nil || len(raw) < headerSize+nonceSize+tagSize || raw[0] != version {
		return nil, id, false
	}

	return raw, [keyIDSize]byte(raw[1:headerSize]), true
}

// additional binds the token header to the caller's additional data.
func additional(header, ad []byte) []byte {
	return bytes.Join([][]byte{header, ad}, nil)
}
