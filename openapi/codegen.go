// TypeScript returns TypeScript declarations for the document: one type per
// component schema, plus <Operation>Body, <Operation>Query and
// <Operation>Response for every operation with an operationId. With zod
// set, Zod schemas (<Name>Schema) for the components follow the types.
func TypeScript(d *Document, zod bool) (string, error) {
	raw, err := json.Marshal(d)
	if err != nil {
		return "", err
	}

	var doc map[string]any
	if err := json.Unmarshal(raw, &doc); err != nil {
		return "", err
	}

	var b strings.Builder

	b.WriteString("// Code generated by vukem codegen:types. DO NOT EDIT.\n\n")

	if zod {
		b.WriteString("import { z } from \"zod\";\n\n")
	}

	schemas := asMap(asMap(doc["components"])["schemas"])
	names := sortedKeys(schemas)

	for _, name := range names {
		fmt.Fprintf(&b, "export type %s = %s;\n\n", tsName(name), tsType(asMap(schemas[name]), ""))
	}

	writeOperationTypes(&b, doc)

	if zod {
		for _, name := range names {
			fmt.Fprintf(&b, "export const %sSchema: z.ZodType<%s, z.ZodTypeDef, unknown> = z.lazy(() =>\n  %s,\n);\n\n",
				tsName(name), tsName(name), zodType(asMap(schemas[name]), "  "))
		}
	}

	return strings.TrimRight(b.String(), "\n") + "\n", nil
}

func writeOperationTypes(b *strings.Builder, doc map[string]any) {
	type op struct {
		id   string
		body map[string]any
	}

	var ops []op

	for _, item := range asMap(doc["paths"]) {
		for _, o := range asMap(item) {
			if id, _ := asMap(o)["operationId"].(string); id != "" {
				ops = append(ops, op{id: id, body: asMap(o)})
			}
		}
	}

	slices.SortFunc(ops, func(a, b op) int { return strings.Compare(a.id, b.id) })

	for _, o := range ops {
		name := tsName(o.id)

		if body := asMap(
			asMap(asMap(asMap(o.body["requestBody"])["content"])["application/json"])["schema"],
		); body != nil {
			fmt.Fprintf(b, "export type %sBody = %s;\n\n", name, tsType(body, ""))
		}

		query := map[string]any{"type": "object", "properties": map[string]any{}}
		var required []any

		for _, p := range asSlice(o.body["parameters"]) {
			pm := asMap(p)
			if pm["in"] != "query" {
				continue
			}

			pname, _ := pm["name"].(string)
			asMap(query["properties"])[pname] = pm["schema"]

			if r, _ := pm["required"].(bool); r {
				required = append(required, pname)
			}
		}

		if len(asMap(query["properties"])) > 0 {
			query["required"] = required
			fmt.Fprintf(b, "export type %sQuery = %s;\n\n", name, tsType(query, ""))
		}

		responses := asMap(o.body["responses"])
		for _, code := range sortedKeys(responses) {
			if len(code) != 3 || code[0] != '2' {
				continue
			}

			typ := "void"
			if sc := asMap(asMap(asMap(asMap(responses[code])["content"])["application/json"])["schema"]); sc != nil {
				typ = tsType(sc, "")
			}

			fmt.Fprintf(b, "export type %sResponse = %s;\n\n", name, typ)

			break
		}
	}
}

// tsName turns "products.store" or "shop.product" into "ProductsStore".
func tsName(s string) string {
	var b strings.Builder

	upper := true

	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upper = true
			continue
		}

		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}

		b.WriteRune(r)
	}

	out := b.String()
	if out == "" || unicode.IsDigit(rune(out[0])) {
		out = "T" + out
	}

	return out
}

func refName(ref string) string { return tsName(ref[strings.LastIndexByte(ref, '/')+1:]) }

var identRe = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func propKey(k string) string {
	if identRe.MatchString(k) {
		return k
	}

	return strconv.Quote(k)
}

func tsType(s map[string]any, indent string) string {
	if ref, ok := s["$ref"].(string); ok {
		return refName(ref)
	}

	if subs := asSlice(s["anyOf"]); len(subs) > 0 {
		return joinTypes(subs, " | ", indent)
	}

	if subs := asSlice(s["allOf"]); len(subs) > 0 {
		return joinTypes(subs, " & ", indent)
	}

	if enum := asSlice(s["enum"]); len(enum) > 0 {
		lits := make([]string, len(enum))
		for i, e := range enum {
			lits[i] = jsonLiteral(e)
		}

		return strings.Join(lits, " | ")
	}

	types := typeList(s["type"])
	if len(types) == 0 {
		return "unknown"
	}

	parts := make([]string, len(types))
	for i, t := range types {
		parts[i] = tsBase(s, t, indent)
	}

	return strings.Join(parts, " | ")
}

func joinTypes(subs []any, sep, indent string) string {
	parts := make([]string, len(subs))
	for i, sub := range subs {
		parts[i] = tsType(asMap(sub), indent)
	}

	return strings.Join(parts, sep)
}

func tsBase(s map[string]any, t, indent string) string {
	switch t {
	case "string":
		return "string"
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "null":
		return "null"
	case "array":
		item := tsType(asMap(s["items"]), indent)
		if strings.ContainsAny(item, "|&") {
			item = "(" + item + ")"
		}

		return item + "[]"
	case "object":
		props := asMap(s["properties"])
		if len(props) == 0 {
			if extra := asMap(s["additionalProperties"]); extra != nil {
				return "Record<string, " + tsType(extra, indent) + ">"
			}

			return "Record<string, unknown>"
		}

		required := map[string]bool{}
		for _, r := range asSlice(s["required"]) {
			if k, ok := r.(string); ok {
				required[k] = true
			}
		}

		var b strings.Builder

		b.WriteString("{\n")

		for _, k := range sortedKeys(props) {
			opt := "?"
			if required[k] {
				opt = ""
			}

			fmt.Fprintf(&b, "%s  %s%s: %s;\n", indent, propKey(k), opt, tsType(asMap(props[k]), indent+"  "))
		}

		b.WriteString(indent + "}")

		return b.String()
	default:
		return "unknown"
	}
}

func zodType(s map[string]any, indent string) string {
	if ref, ok := s["$ref"].(string); ok {
		return refName(ref) + "Schema"
	}

	if subs := asSlice(s["anyOf"]); len(subs) > 0 {
		return zodUnion(subs, indent)
	}

	if subs := asSlice(s["allOf"]); len(subs) > 0 {
		out := zodType(asMap(subs[0]), indent)
		for _, sub := range subs[1:] {
			out = "z.intersection(" + out + ", " + zodType(asMap(sub), indent) + ")"
		}

		return out
	}

	types := typeList(s["type"])
	nullable := slices.Contains(types, "null")
	types = slices.DeleteFunc(types, func(t string) bool { return t == "null" })

	var out string

	switch {
	case len(asSlice(s["enum"])) > 0:
		out = zodEnum(asSlice(s["enum"]))
	case len(types) == 0 && nullable:
		return "z.null()"
	case len(types) == 0:
		return "z.unknown()"
	case len(types) > 1:
		subs := make([]any, len(types))
		for i, t := range types {
			subs[i] = map[string]any{"type": t}
		}

		out = zodUnion(subs, indent)
	default:
		out = zodBase(s, types[0], indent)
	}

	if nullable {
		out += ".nullable()"
	}

	return out
}

func zodUnion(subs []any, indent string) string {
	var nonNull []string

	hasNull := false

	for _, sub := range subs {
		if typeList(asMap(sub)["type"]) != nil && slices.Equal(typeList(asMap(sub)["type"]), []string{"null"}) {
			hasNull = true
			continue
		}

		nonNull = append(nonNull, zodType(asMap(sub), indent))
	}

	var out string

	switch len(nonNull) {
	case 0:
		out = "z.null()"
		hasNull = false
	case 1:
		out = nonNull[0]
	default:
		out = "z.union([" + strings.Join(nonNull, ", ") + "])"
	}

	if hasNull {
		out += ".nullable()"
	}

	return out
}

func zodEnum(enum []any) string {
	parts := make([]string, 0, len(enum))

	for _, e := range enum {
		if e == nil {
			continue
		}

		parts = append(parts, "z.literal("+jsonLiteral(e)+")")
	}

	if len(parts) == 1 {
		return parts[0]
	}

	return "z.union([" + strings.Join(parts, ", ") + "])"
}

func zodBase(s map[string]any, t, indent string) string {
	num := func(k string) (string, bool) {
		v, ok := s[k].(float64)
		return strconv.FormatFloat(v, 'f', -1, 64), ok
	}

	var b strings.Builder

	switch t {
	case "string":
		b.WriteString("z.string()")

		switch s["format"] {
		case "email":
			b.WriteString(".email()")
		case "uri":
			b.WriteString(".url()")
		case "uuid":
			b.WriteString(".uuid()")
		case "date-time":
			b.WriteString(".datetime({ offset: true })")
		}

		if v, ok := num("minLength"); ok {
			b.WriteString(".min(" + v + ")")
		}

		if v, ok := num("maxLength"); ok {
			b.WriteString(".max(" + v + ")")
		}

		if p, ok := s["pattern"].(string); ok {
			b.WriteString(".regex(new RegExp(" + strconv.Quote(p) + ", \"u\"))")
		}
	case "integer", "number":
		b.WriteString("z.number()")

		if t == "integer" {
			b.WriteString(".int()")
		}

		for _, km := range [][2]string{{"minimum", "gte"}, {"maximum", "lte"}, {"exclusiveMinimum", "gt"}, {"multipleOf", "multipleOf"}} {
			if v, ok := num(km[0]); ok {
				b.WriteString("." + km[1] + "(" + v + ")")
			}
		}
	case "boolean":
		b.WriteString("z.boolean()")
	case "array":
		b.WriteString("z.array(" + zodType(asMap(s["items"]), indent) + ")")

		if v, ok := num("minItems"); ok {
			b.WriteString(".min(" + v + ")")
		}

		if v, ok := num("maxItems"); ok {
			b.WriteString(".max(" + v + ")")
		}
	case "object":
		props := asMap(s["properties"])
		if len(props) == 0 {
			if extra := asMap(s["additionalProperties"]); extra != nil {
				return "z.record(z.string(), " + zodType(extra, indent) + ")"
			}

			return "z.record(z.string(), z.unknown())"
		}

		required := map[string]bool{}
		for _, r := range asSlice(s["required"]) {
			if k, ok := r.(string); ok {
				required[k] = true
			}
		}

		b.WriteString("z.object({\n")

		for _, k := range sortedKeys(props) {
			v := zodType(asMap(props[k]), indent+"  ")
			if !required[k] {
				v += ".optional()"
			}

			fmt.Fprintf(&b, "%s  %s: %s,\n", indent, propKey(k), v)
		}

		b.WriteString(indent + "})")

		if s["additionalProperties"] == false {
			b.WriteString(".strict()")
		}
	default:
		return "z.unknown()"
	}

	return b.String()
}

func typeList(t any) []string {
	switch t := t.(type) {
	case string:
		return []string{t}
	case []any:
		out := make([]string, 0, len(t))
		for _, x := range t {
			if s, ok := x.(string); ok {
				out = append(out, s)
			}
		}

		return out
	}

	return nil
}

func asSlice(v any) []any {
	s, _ := v.([]any)
	return s
}

func sortedKeys(m map[string]any) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}

	slices.Sort(keys)

	return keys
}

// jsonLiteral renders an enum member (decoded JSON: string, number, bool,
// nil) as a TypeScript literal.
func jsonLiteral(v any) string {
	switch v := v.(type) {
	case string:
		return strconv.Quote(v)
	case float64:
		return strconv.FormatFloat(v, 'f', -1, 64)
	case bool:
		return strconv.FormatBool(v)
	default:
		return "null"
	}
}
