func runApp(t *testing.T, args ...string) (string, error) {
	t.Helper()

	var out bytes.Buffer

	build := func(opts ...Option) (*App, error) {
		return New(append(opts,
			WithLogger(discardLogger()), WithStdout(&out),
			WithProviders(&connectingProvider{}), WithRoutes(openAPIRoutes))...)
	}

	err := RunMain(t.Context(), append([]string{"app"}, args...), testSource(nil).Lookup, build)

	return out.String(), err
}

func TestCodegenClientCommand_Style(t *testing.T) {
	t.Parallel()

	got, err := runApp(t, "codegen:client", "-style", "throw", "-o", "-")
	if err != nil {
		t.Fatal(err)
	}

	for _, want := range []string{
		"// Code generated by vukem codegen:client -style throw. DO NOT EDIT.",
		"ping(): Promise<PingResponse>;",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("-style throw output lacks %q", want)
		}
	}

	got, err = runApp(t, "codegen:client", "-tanstack", "-prefix", "/api", "-o", "-")
	if err != nil {
		t.Fatal(err)
	}

	for _, want := range []string{
		"// Code generated by vukem codegen:client -tanstack -prefix /api. DO NOT EDIT.",
		"export function createQueries(client: Client)",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("-tanstack output lacks %q", want)
		}
	}
}

func TestCodegenClientCommand_BadFlags(t *testing.T) {
	t.Parallel()

	for _, args := range [][]string{
		{"-lang", "go", "-style", "throw", "-o", "-"},
		{"-lang", "go", "-tanstack", "-o", "-"},
		{"-style", "promise", "-o", "-"},
		{"-style", "throw", "-tanstack", "-o", "-"},
		{"-check", "-o", "-"},
	} {
		if _, err := runApp(t, append([]string{"codegen:client"}, args...)...); err == nil {
			t.Errorf("codegen:client %v = nil error", args)
		}
	}

	if _, err := runApp(t, "codegen:routes", "-check", "-o", "-"); err == nil {
		t.Error("codegen:routes -check -o - = nil error")
	}
}

func TestCodegenCheck(t *testing.T) {
	t.Parallel()

	for _, cmd := range []string{"codegen:client", "codegen:routes"} {
		path := filepath.Join(t.TempDir(), "out.ts")

		_, err := runApp(t, cmd, "-check", "-o", path)
		if err == nil || !strings.Contains(err.Error(), "is stale: run \""+"vukem "+cmd+"\"") {
			t.Fatalf("%s -check on a missing file = %v", cmd, err)
		}

		if _, err := os.Stat(path); err == nil {
			t.Fatalf("%s -check wrote the file", cmd)
		}

		if _, err := runApp(t, cmd, "-o", path); err != nil {
			t.Fatal(err)
		}

		if _, err := runApp(t, cmd, "-check", "-o", path); err != nil {
			t.Errorf("%s -check on a fresh file = %v", cmd, err)
		}

		if err := os.WriteFile(path, []byte("// edited\n"), 0o600); err != nil {
			t.Fatal(err)
		}

		if _, err := runApp(t, cmd, "-check", "-o", path); err == nil {
			t.Errorf("%s -check on an edited file = nil", cmd)
		}
	}
}

func TestGeneratedArgs(t *testing.T) {
	t.Parallel()

	tests := []struct {
		line     string
		command  string
		args     []string
		wantOK   bool
		describe string
	}{
		{"// Code generated by vukem codegen:routes. DO NOT EDIT.", "codegen:routes", []string{}, true, "no flags"},
		{
			"// Code generated by vukem codegen:client -style throw -tanstack -prefix /api. DO NOT EDIT.\r",
			"codegen:client",
			[]string{"-style", "throw", "-tanstack", "-prefix", "/api"},
			true,
			"flags",
		},
		{
			"// Code generated by vukem codegen:client -style throw; rm -rf /. DO NOT EDIT.",
			"",
			nil,
			false,
			"shell text",
		},
		{"// Code generated by vukem codegen:client $(id). DO NOT EDIT.", "", nil, false, "substitution"},
		{"// Code generated by vukem codegen:client -style  throw. DO NOT EDIT.", "", nil, false, "double space"},
		{"// Code generated by vukem codegen:client -style throw extra. DO NOT EDIT.", "", nil, false, "stray word"},
		{"// Code generated by vukem make:model. DO NOT EDIT.", "", nil, false, "not codegen"},
		{"package main", "", nil, false, "not a header"},
	}

	for _, tt := range tests {
		t.Run(tt.describe, func(t *testing.T) {
			t.Parallel()

			command, args, ok := generatedArgs(tt.line)
			if ok != tt.wantOK || command != tt.command || !slices.Equal(args, tt.args) {
				t.Errorf("generatedArgs(%q) = %q, %q, %v", tt.line, command, args, ok)
			}
		})
	}
}

// The "codegen" command regenerates the files that exist with the flags their
// header records, and leaves the rest alone.
func TestCodegenCommand(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)

	api := filepath.Join(dir, "resources", "js", "api.ts")
	routes := filepath.Join(dir, "resources", "js", "routes.ts")

	if err := os.MkdirAll(filepath.Dir(api), 0o750); err != nil {
		t.Fatal(err)
	}

	if err := os.WriteFile(
		api,
		[]byte("// Code generated by vukem codegen:client -style throw. DO NOT EDIT.\nstale\n"),
		0o600,
	); err != nil {
		t.Fatal(err)
	}

	if _, err := runApp(t, "codegen", "-check"); err == nil || !strings.Contains(err.Error(), "is stale") {
		t.Fatalf("codegen -check on a stale file = %v", err)
	}

	if _, err := runApp(t, "codegen"); err != nil {
		t.Fatal(err)
	}

	want, err := runApp(t, "codegen:client", "-style", "throw", "-o", "-")
	if err != nil {
		t.Fatal(err)
	}

	got, err := os.ReadFile(api)
	if err != nil {
		t.Fatal(err)
	}

	if diff := cmp.Diff(want, string(got)); diff != "" {
		t.Errorf("api.ts is not the throw client (-want +got):\n%s", diff)
	}

	if _, err := os.Stat(routes); err == nil {
		t.Error("codegen created routes.ts, which the app did not have")
	}

	if _, err := runApp(t, "codegen", "-check"); err != nil {
		t.Errorf("codegen -check after codegen = %v", err)
	}

	// A file that is not the generator's output is reported, never overwritten.
	if err := os.WriteFile(api, []byte("export const mine = 1;\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	if _, err := runApp(t, "codegen"); err == nil {
		t.Error("codegen overwrote a file without the generated header")
	}

	if b, _ := os.ReadFile(api); string(b) != "export const mine = 1;\n" {
		t.Errorf("api.ts = %q", b)
	}
}
