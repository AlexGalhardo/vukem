package vukem

import (
	"context"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/AlexGalhardo/vukem/router"
)

const defaultRoutesTS = "resources/js/routes.ts"

func codegenRoutesCommand() Command {
	var out *string

	return CommandFunc{
		CommandName: "codegen:routes",
		Desc:        "Generate typed frontend routes (resources/js/routes.ts; -o - prints to stdout)",
		DefineFlags: func(fs *flag.FlagSet) {
			out = fs.String("o", defaultRoutesTS, `write to this file ("-" for stdout)`)
		},
		Fn: func(_ context.Context, app *App, _ []string) error {
			if _, err := app.Router.Handler(); err != nil {
				return err
			}

			ts := routesTypeScript(app.Router.Routes())

			if *out == "-" {
				_, err := io.WriteString(app.stdout, ts)
				return err
			}

			path := filepath.FromSlash(*out)
			if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
				return fmt.Errorf("codegen:routes: %w", err)
			}

			return os.WriteFile(path, []byte(ts), 0o600)
		},
	}
}

type tsRoute struct {
	name, method, path string
	params             []string
}

// routesTypeScript renders the named routes as a typed TypeScript module.
func routesTypeScript(infos []router.RouteInfo) string {
	var named []tsRoute

	for _, ri := range infos {
		if ri.Name == "" {
			continue
		}

		path := strings.ReplaceAll(ri.Path, "{$}", "")
		if path == "" {
			path = "/"
		}

		named = append(named, tsRoute{name: ri.Name, method: ri.Method, path: path, params: pathParams(path)})
	}

	slices.SortFunc(named, func(a, b tsRoute) int { return strings.Compare(a.name, b.name) })

	var b strings.Builder

	b.WriteString("// Code generated by vukem codegen:routes. DO NOT EDIT.\n\n")
	b.WriteString("export const routes = {\n")

	for _, r := range named {
		fmt.Fprintf(&b, "  %s: { method: %s, path: %s },\n",
			strconv.Quote(r.name), strconv.Quote(r.method), strconv.Quote(r.path))
	}

	b.WriteString("} as const;\n\n")
	b.WriteString("export type RouteName = keyof typeof routes;\n\n")
	b.WriteString("export type RouteParam = string | number;\n\n")
	b.WriteString("export type RouteQuery = Record<string, string | number | boolean | null | undefined>;\n\n")
	b.WriteString("export interface RouteParams {\n")

	for _, r := range named {
		fmt.Fprintf(&b, "  %s: %s;\n", strconv.Quote(r.name), paramsType(r.params))
	}

	b.WriteString("}\n")
	b.WriteString(routeFuncTS)

	return b.String()
}

func paramsType(params []string) string {
	if len(params) == 0 {
		return "Record<string, never>"
	}

	fields := make([]string, len(params))
	for i, p := range params {
		fields[i] = strconv.Quote(p) + ": RouteParam"
	}

	return "{ " + strings.Join(fields, "; ") + " }"
}

// pathParams returns the wildcard names of a ServeMux pattern path.
func pathParams(path string) []string {
	var names []string

	for rest := path; ; {
		start := strings.IndexByte(rest, '{')
		if start < 0 {
			return names
		}

		end := strings.IndexByte(rest[start:], '}')
		if end < 0 {
			return names
		}

		names = append(names, strings.TrimSuffix(rest[start+1:start+end], "..."))
		rest = rest[start+end+1:]
	}
}

// routeFuncTS mirrors router.URL: "{name...}" keeps "/" and encodes each
// segment. It sticks to ES5 library calls so it type-checks under any lib.
const routeFuncTS = `
type RouteArgs<N extends RouteName> = RouteParams[N] extends Record<string, never>
  ? [params?: RouteParams[N], query?: RouteQuery]
  : [params: RouteParams[N], query?: RouteQuery];

/** route builds the URL of a named route, e.g. route("posts.show", { id: 7 }). */
export function route<N extends RouteName>(name: N, ...args: RouteArgs<N>): string {
  const params = (args[0] ?? {}) as Record<string, RouteParam | undefined>;
  const query = args[1];
  let url = (routes[name].path as string).replace(/\{([^}]+)\}/g, (_match: string, wild: string): string => {
    const multi = wild.slice(-3) === "...";
    const key = multi ? wild.slice(0, -3) : wild;
    const value = params[key];
    if (value === undefined) {
      throw new Error("route(" + name + "): missing param " + key);
    }
    const raw = String(value);
    return multi ? raw.split("/").map(encodeURIComponent).join("/") : encodeURIComponent(raw);
  });
  if (query) {
    const parts: string[] = [];
    for (const key of Object.keys(query)) {
      const value = query[key];
      if (value !== undefined && value !== null) {
        parts.push(encodeURIComponent(key) + "=" + encodeURIComponent(String(value)));
      }
    }
    if (parts.length > 0) {
      url += "?" + parts.join("&");
    }
  }
  return url;
}
`
