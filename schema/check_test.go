func TestCheckDDL(t *testing.T) {
	t.Parallel()

	create := func(s *Schema) error {
		return s.Create("raffles", func(t *Table) {
			t.ID()
			t.Integer("number_count")
			t.Check("raffles_number_count_check", "number_count BETWEEN 10 AND 1000")
		})
	}
	alter := func(s *Schema) error {
		return s.Table("raffles", func(t *Table) {
			t.Check("raffles_positive_check", "number_count > 0")
			t.DropCheck("raffles_number_count_check")
		})
	}

	tests := []struct {
		name string
		d    database.Dialect
		fn   func(*Schema) error
		want []string
	}{
		{"sqlite create", database.SQLite, create, []string{`CREATE TABLE "raffles" (
  "id" INTEGER PRIMARY KEY AUTOINCREMENT,
  "number_count" INTEGER NOT NULL,
  CONSTRAINT "raffles_number_count_check" CHECK (number_count BETWEEN 10 AND 1000)
)`}},
		{"postgres create", database.Postgres, create, []string{`CREATE TABLE "raffles" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "number_count" INTEGER NOT NULL,
  CONSTRAINT "raffles_number_count_check" CHECK (number_count BETWEEN 10 AND 1000)
)`}},
		{"mysql create", database.MySQL, create, []string{"CREATE TABLE `raffles` (\n" +
			"  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,\n" +
			"  `number_count` INT NOT NULL,\n" +
			"  CONSTRAINT `raffles_number_count_check` CHECK (number_count BETWEEN 10 AND 1000)\n)"}},
		{"postgres alter", database.Postgres, alter, []string{
			`ALTER TABLE "raffles" DROP CONSTRAINT "raffles_number_count_check"`,
			`ALTER TABLE "raffles" ADD CONSTRAINT "raffles_positive_check" CHECK (number_count > 0)`,
		}},
		{"mysql alter", database.MySQL, alter, []string{
			"ALTER TABLE `raffles` DROP CONSTRAINT `raffles_number_count_check`",
			"ALTER TABLE `raffles` ADD CONSTRAINT `raffles_positive_check` CHECK (number_count > 0)",
		}},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			if diff := cmp.Diff(tt.want, record(t, tt.d, tt.fn)); diff != "" {
				t.Fatalf("DDL mismatch (-want +got):\n%s", diff)
			}
		})
	}
}

func TestCheckErrors(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		d    database.Dialect
		fn   func(*Schema) error
		want string
	}{
		{"bad name", database.Postgres, func(s *Schema) error {
			return s.Create("t", func(t *Table) { t.Check("bad name", "x > 0") })
		}, "invalid check name"},
		{"empty expression", database.Postgres, func(s *Schema) error {
			return s.Create("t", func(t *Table) { t.Check("t_check", "  ") })
		}, "needs an expression"},
		{"sqlite add to existing table", database.SQLite, func(s *Schema) error {
			return s.Table("t", func(t *Table) { t.Check("t_check", "x > 0") })
		}, "sqlite cannot add a check"},
		{"sqlite drop from existing table", database.SQLite, func(s *Schema) error {
			return s.Table("t", func(t *Table) { t.DropCheck("t_check") })
		}, "sqlite cannot drop a check"},
		{"drop check on create", database.Postgres, func(s *Schema) error {
			return s.Create("t", func(t *Table) { t.ID(); t.DropCheck("t_check") })
		}, "alter only"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			s, stmts := recorder(tt.d)

			err := tt.fn(s)
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("err = %v, want containing %q", err, tt.want)
			}

			if len(*stmts) != 0 {
				t.Fatalf("statements ran despite the error: %q", *stmts)
			}
		})
	}
}

func TestCheckEnforcedOnSQLite(t *testing.T) {
	t.Parallel()

	db := openDB(t)
	s := New(t.Context(), db)

	if err := s.Create("raffles", func(t *Table) {
		t.ID()
		t.Integer("number_count")
		t.Check("raffles_number_count_check", "number_count BETWEEN 10 AND 1000")
	}); err != nil {
		t.Fatal(err)
	}

	if _, err := db.ExecContext(t.Context(), "INSERT INTO raffles (number_count) VALUES (?)", 100); err != nil {
		t.Fatalf("valid row: %v", err)
	}

	_, err := db.ExecContext(t.Context(), "INSERT INTO raffles (number_count) VALUES (?)", 5)
	if err == nil || !strings.Contains(err.Error(), "raffles_number_count_check") {
		t.Fatalf("invalid row err = %v, want the named CHECK to fail", err)
	}
}
