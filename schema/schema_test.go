func usersPosts(s *Schema) error {
	if err := s.Create("users", func(t *Table) {
		t.ID()
		t.String("name")
		t.String("email", 191).Unique()
		t.Boolean("active").Default(true)
		t.Integer("age").Default(0)
		t.Decimal("balance", 10, 2).Default(0.5)
		t.Enum("role", "admin", "user").Default("user")
		t.JSON("settings").Nullable()
		t.UUID("public_id").Nullable()
		t.ULID("ulid").Nullable()
		t.Text("bio").Nullable().Default("it's me")
		t.Float("score").Nullable()
		t.Date("born_on").Nullable()
		t.Binary("avatar").Nullable()
		t.Timestamp("verified_at").Nullable().Default(Expr("CURRENT_TIMESTAMP"))
		t.Timestamps()
		t.Index("name", "age")
	}); err != nil {
		return err
	}

	return s.Create("posts", func(t *Table) {
		t.ID()
		t.ForeignID("user_id").Constrained().CascadeOnDelete()
		t.String("title").Index()
		t.SoftDeletes()
		t.Timestamps()
		t.UniqueIndex("user_id", "title")
	})
}

func record(t *testing.T, d database.Dialect, fn func(*Schema) error) []string {
	t.Helper()

	s, stmts := recorder(d)
	if err := fn(s); err != nil {
		t.Fatal(err)
	}

	return *stmts
}

func TestSQLiteDDL(t *testing.T) {
	t.Parallel()

	got := record(t, database.SQLite, usersPosts)
	want := []string{
		`CREATE TABLE "users" (
  "id" INTEGER PRIMARY KEY AUTOINCREMENT,
  "name" VARCHAR(255) NOT NULL,
  "email" VARCHAR(191) NOT NULL UNIQUE,
  "active" BOOLEAN NOT NULL DEFAULT TRUE,
  "age" INTEGER NOT NULL DEFAULT 0,
  "balance" NUMERIC(10, 2) NOT NULL DEFAULT 0.5,
  "role" TEXT NOT NULL DEFAULT 'user' CHECK ("role" IN ('admin', 'user')),
  "settings" TEXT,
  "public_id" TEXT,
  "ulid" CHAR(26),
  "bio" TEXT DEFAULT 'it''s me',
  "score" REAL,
  "born_on" DATE,
  "avatar" BLOB,
  "verified_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  "created_at" TIMESTAMP,
  "updated_at" TIMESTAMP
)`,
		`CREATE INDEX "users_name_age_index" ON "users" ("name", "age")`,
		`CREATE TABLE "posts" (
  "id" INTEGER PRIMARY KEY AUTOINCREMENT,
  "user_id" INTEGER NOT NULL,
  "title" VARCHAR(255) NOT NULL,
  "deleted_at" TIMESTAMP,
  "created_at" TIMESTAMP,
  "updated_at" TIMESTAMP,
  FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE CASCADE
)`,
		`CREATE INDEX "posts_title_index" ON "posts" ("title")`,
		`CREATE UNIQUE INDEX "posts_user_id_title_unique" ON "posts" ("user_id", "title")`,
	}

	if diff := cmp.Diff(want, got); diff != "" {
		t.Fatalf("DDL mismatch (-want +got):\n%s", diff)
	}
}

func TestPostgresDDL(t *testing.T) {
	t.Parallel()

	got := strings.Join(record(t, database.Postgres, usersPosts), "\n")

	for _, frag := range []string{
		`"id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`,
		`"settings" JSONB`,
		`"public_id" UUID`,
		`"score" DOUBLE PRECISION`,
		`"avatar" BYTEA`,
		`"verified_at" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP`,
		`"user_id" BIGINT NOT NULL`,
	} {
		if !strings.Contains(got, frag) {
			t.Errorf("postgres DDL missing %q", frag)
		}
	}

	drop := record(t, database.Postgres, func(s *Schema) error { return s.Drop("users") })
	if drop[0] != `DROP TABLE "users" CASCADE` {
		t.Fatalf("drop = %q", drop[0])
	}
}

func openDB(t *testing.T) *database.DB {
	t.Helper()

	db, err := database.Open(t.Context(), "file:"+filepath.Join(t.TempDir(), "m.db"))
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = db.Close() })

	return db
}

func TestApplyOnSQLite(t *testing.T) {
	t.Parallel()

	db := openDB(t)
	ctx := t.Context()
	s := New(ctx, db)

	if err := usersPosts(s); err != nil {
		t.Fatal(err)
	}

	if ok, _ := s.HasTable("posts"); !ok {
		t.Fatal("posts not created")
	}

	_, _ = db.ExecContext(ctx, `INSERT INTO users (name, email) VALUES ('a', 'a@x.io')`)
	_, _ = db.ExecContext(ctx, `INSERT INTO posts (user_id, title) VALUES (1, 't')`)

	if _, err := db.ExecContext(
		ctx,
		`INSERT INTO users (name, email, role) VALUES ('b', 'b@x.io', 'root')`,
	); err == nil {
		t.Fatal("enum CHECK not enforced")
	}
	if _, err := db.ExecContext(ctx, `INSERT INTO posts (user_id, title) VALUES (99, 't')`); err == nil {
		t.Fatal("foreign key not enforced")
	}

	_, _ = db.ExecContext(ctx, `DELETE FROM users WHERE id = 1`)
	var n int
	_ = db.QueryRowContext(ctx, `SELECT COUNT(*) FROM posts`).Scan(&n)
	if n != 0 {
		t.Fatal("ON DELETE CASCADE not applied")
	}

	err := s.Table("users", func(t *Table) {
		t.String("nickname").Nullable()
		t.ForeignID("manager_id").Nullable().Constrained("users").NullOnDelete()
		t.RenameColumn("bio", "about")
		t.Index("nickname")
	})
	if err != nil {
		t.Fatal(err)
	}

	if err := s.Table("users", func(t *Table) {
		t.DropIndex("users_nickname_index")
		t.DropColumn("nickname")
	}); err != nil {
		t.Fatal(err)
	}

	if err := s.Rename("posts", "articles"); err != nil {
		t.Fatal(err)
	}
	if err := s.Raw(`CREATE VIEW active_users AS SELECT * FROM users WHERE active`); err != nil {
		t.Fatal(err)
	}
	if err := s.DropIfExists("articles"); err != nil || s.DropIfExists("nope") != nil {
		t.Fatal(err)
	}
	if err := s.Drop("articles"); err == nil {
		t.Fatal("Drop missing table succeeded")
	}
	if s.Dialect() != "sqlite" {
		t.Fatal("dialect")
	}
}

func TestSecurity_A05_SchemaRejectsBadIdentifiers(t *testing.T) {
	t.Parallel()

	s, _ := recorder(database.SQLite)

	cases := []func() error{
		func() error { return s.Create("users; DROP TABLE x", func(*Table) {}) },
		func() error { return s.Create("ok", func(t *Table) { t.String("bad col") }) },
		func() error { return s.Create("ok", func(t *Table) { t.Index("a;b") }) },
		func() error { return s.Create("ok", func(t *Table) { t.ForeignID("x").Constrained("t;--") }) },
		func() error { return s.Create("ok", func(t *Table) { t.Enum("e") }) },
		func() error { return s.Create("ok", func(t *Table) { t.Integer("n").CascadeOnDelete() }) },
		func() error { return s.Table("ok", func(t *Table) { t.ID() }) },
		func() error { return s.Table("bad name", func(*Table) {}) },
		func() error { return s.Table("ok", func(t *Table) { t.RenameColumn("a b", "c") }) },
		func() error { return s.Table("ok", func(t *Table) { t.DropColumn("a;") }) },
		func() error { return s.Table("ok", func(t *Table) { t.DropIndex("i x") }) },
		func() error { return s.Drop("x y") },
		func() error { return s.DropIfExists("x y") },
		func() error { return s.Rename("a", "b c") },
		func() error { return s.Rename("a b", "c") },
	}

	for i, c := range cases {
		if err := c(); err == nil {
			t.Errorf("case %d accepted invalid input", i)
		}
	}

	if literal("x'; DROP TABLE users; --") != "'x''; DROP TABLE users; --'" {
		t.Fatal("string defaults not escaped")
	}
	if literal(nil) != "NULL" || literal(false) != "FALSE" || literal(float32(1.5)) != "1.5" ||
		literal(struct{}{}) != "'{}'" {
		t.Fatal("literals")
	}
}

func migrations(extra ...Migration) []Migration {
	base := []Migration{
		{
			ID: "20260101000000_create_users",
			Up: func(s *Schema) error {
				return s.Create("users", func(t *Table) { t.ID(); t.String("email") })
			},
			Down: func(s *Schema) error { return s.Drop("users") },
		},
		{
			ID: "20260102000000_create_posts",
			Up: func(s *Schema) error {
				return s.Create("posts", func(t *Table) { t.ID(); t.ForeignID("user_id").Constrained() })
			},
			Down: func(s *Schema) error { return s.Drop("posts") },
		},
	}

	return append(base, extra...)
}

func TestMigrator(t *testing.T) {
	t.Parallel()

	db := openDB(t)
	ctx := t.Context()

	m, err := NewMigrator(db, migrations())
	if err != nil {
		t.Fatal(err)
	}

	ran, err := m.Up(ctx)
	if err != nil || len(ran) != 2 {
		t.Fatalf("Up = %v %v", ran, err)
	}
	if ran, _ := m.Up(ctx); len(ran) != 0 {
		t.Fatal("Up is not idempotent")
	}

	// Second batch.
	m2, _ := NewMigrator(db, migrations(Migration{
		ID:   "20260103000000_add_name",
		Up:   func(s *Schema) error { return s.Table("users", func(t *Table) { t.String("name").Nullable() }) },
		Down: func(s *Schema) error { return s.Table("users", func(t *Table) { t.DropColumn("name") }) },
	}))
	if ran, err := m2.Up(ctx); err != nil || len(ran) != 1 {
		t.Fatalf("batch 2 = %v %v", ran, err)
	}

	st, err := m2.Status(ctx)
	if err != nil || len(st) != 3 || st[2].Batch != 2 || st[0].Batch != 1 || st[0].Changed || st[0].RanAt.IsZero() {
		t.Fatalf("Status = %+v %v", st, err)
	}

	// Rollback reverts only the last batch.
	if back, err := m2.Rollback(ctx, 0); err != nil || len(back) != 1 || back[0] != "20260103000000_add_name" {
		t.Fatalf("Rollback = %v %v", back, err)
	}

	// Steps.
	if back, err := m2.Rollback(ctx, 1); err != nil || len(back) != 1 || back[0] != "20260102000000_create_posts" {
		t.Fatalf("Rollback(1) = %v %v", back, err)
	}

	if _, err := m2.Up(ctx); err != nil {
		t.Fatal(err)
	}

	if back, err := m2.Reset(ctx); err != nil || len(back) != 3 {
		t.Fatalf("Reset = %v %v", back, err)
	}
	if back, _ := m2.Rollback(ctx, 0); back != nil {
		t.Fatal("Rollback on empty")
	}

	if ran, err := m2.Fresh(ctx); err != nil || len(ran) != 3 {
		t.Fatalf("Fresh = %v %v", ran, err)
	}
	if ok, _ := hasTable(ctx, db, "posts"); !ok {
		t.Fatal("Fresh did not recreate tables")
	}
}

func TestMigratorChangedAndMissing(t *testing.T) {
	t.Parallel()

	db := openDB(t)
	ctx := t.Context()

	m, _ := NewMigrator(db, migrations())
	if _, err := m.Up(ctx); err != nil {
		t.Fatal(err)
	}

	edited := migrations()
	edited[0].Up = func(s *Schema) error {
		return s.Create("users", func(t *Table) { t.ID(); t.String("email"); t.String("extra") })
	}
	edited = edited[:1] // second migration removed from code

	m2, _ := NewMigrator(db, edited)

	st, err := m2.Status(ctx)
	if err != nil {
		t.Fatal(err)
	}

	if !st[0].Changed || !st[1].Missing {
		t.Fatalf("Status = %+v", st)
	}

	if _, err := m2.Rollback(ctx, 1); err == nil || !strings.Contains(err.Error(), "missing from code") {
		t.Fatalf("rollback of missing migration = %v", err)
	}
}

func TestMigratorErrors(t *testing.T) {
	t.Parallel()

	db := openDB(t)
	ctx := t.Context()

	if _, err := NewMigrator(db, []Migration{{ID: "a"}}); err == nil {
		t.Error("migration without Up accepted")
	}
	if _, err := NewMigrator(db, []Migration{{ID: "a", Up: usersPosts}, {ID: "a", Up: usersPosts}}); err == nil {
		t.Error("duplicate IDs accepted")
	}

	boom := errors.New("boom")
	failing, _ := NewMigrator(db, []Migration{
		{ID: "1", Up: func(s *Schema) error {
			if err := s.Create("half", func(t *Table) { t.ID() }); err != nil {
				return err
			}
			if s.record != nil {
				return nil
			}
			return boom
		}},
	})

	if _, err := failing.Up(ctx); !errors.Is(err, boom) {
		t.Fatalf("Up error = %v", err)
	}
	if ok, _ := hasTable(ctx, db, "half"); ok {
		t.Fatal("failed migration was not rolled back")
	}

	noDown, _ := NewMigrator(
		db,
		[]Migration{{ID: "x", Up: func(s *Schema) error { return s.Create("x", func(t *Table) { t.ID() }) }}},
	)
	_, _ = noDown.Up(ctx)
	if _, err := noDown.Rollback(ctx, 0); err == nil || !strings.Contains(err.Error(), "no Down") {
		t.Fatalf("rollback without Down = %v", err)
	}

	badSQL, _ := NewMigrator(
		db,
		[]Migration{{ID: "y", Up: func(*Schema) error { return errors.New("checksum fails") }}},
	)
	if _, err := badSQL.Up(ctx); err == nil {
		t.Fatal("checksum error ignored")
	}

	_ = db.Close()
	if _, err := failing.Status(context.Background()); err == nil {
		t.Fatal("Status on closed db")
	}
}
